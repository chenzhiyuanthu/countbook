export type StringKey = keyof typeof STRINGS

export const WEEKDAYS: Record<Locale, string[]> = {
  'zh-CN': ['周日', '周一', '周二', '周三', '周四', '周五', '周六'],
  en: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'],
}

export function translate(locale: Locale, key: StringKey, vars?: Record<string, string | number>): string {
  const pair = STRINGS[key] as readonly [string, string]
  let s = locale === 'en' ? pair[1] : pair[0]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

export const makeT =
  (locale: Locale) =>
  (key: StringKey, vars?: Record<string, string | number>): string =>
    translate(locale, key, vars)

export type T = ReturnType<typeof makeT>
